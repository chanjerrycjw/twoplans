import Foundation

/// 计划中的一个模块（学习计划的「周」，唱歌计划的「周块 / 月块」）
struct PlanBlock: Identifiable {
    let id = UUID()
    /// 所属计划月份（1-12）
    let month: Int
    /// 该模块在「公式周」空间覆盖的范围（学习每块 1 周；唱歌前 3 月按周、第 4-12 月按 4 周一个月块）
    let weekRange: ClosedRange<Int>
    /// 显示标签，如「第1周」「第5-6周」「第4个月」
    let label: String
    /// 模块标题
    let title: String
    /// 练习 / 任务要点（作为「今日任务」可勾选清单）
    let items: [String]
}

/// 一个完整年度计划的描述
struct PlanData {
    /// 稳定标识，用于持久化 key 区分两个计划
    let id: String
    /// 显示名（用于 Tab 与导航标题）
    let name: String
    /// 总天数上限（学习 360，唱歌 365）
    let totalDays: Int
    /// 12 个月各自的天数，用于月份网格的完成比例
    let monthDurations: [Int]
    /// 全部模块
    let blocks: [PlanBlock]
    /// 按星期几（周一~周日）的每日练习菜单，仅唱歌计划有
    let dailyMenu: [String: [String]]
    /// 按月份的月度检查点清单，仅唱歌计划有
    let monthlyCheckpoints: [Int: [String]]
}

// MARK: - 学习计划（AI 学习，12 月 × 4 周 = 48 周）

private func studyBlock(_ month: Int, _ week: Int, _ title: String, _ items: [String]) -> PlanBlock {
    PlanBlock(month: month, weekRange: week...week, label: "第\(week)周", title: title, items: items)
}

